#!/usr/bin/env python3
"""BEATMAP.md + audit/timeline-by-second.txt for DYK No. 02, from the SAME data the mix uses
(timeline.json, vo.json, cues.py via build_final's resolver). One row per second of the master:
shot · words spoken · visual events (with their SFX). Flags narrated stretches of >= 2 s with no
visual event, so every one can be checked (continuous motion) or fixed before rendering."""
import os, sys
WORK = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, WORK)
import build_final as B  # noqa: E402  (pure timing; main() is not run)

GAP_S = 2.6   # >= 2.6 s listed (all >= 2.9 s gaps were given a beat in pass 2)
# continuous motion that carries the picture between discrete events (checked on stills)
MOTION = {
    'SuHook': 'Sun rising (0-4 s), silhouette glow, photon travelling, countdown ticking',
    'SuPromise': 'Sun rising, people lighting in 12-frame steps', 'Su1500': 'bonfires flicker, Day Clock drawing, orbiting Sun',
    'Su1610': 'mist drift, spots drifting across the turning Sun, Day Clock drawing',
    'Su1700': 'parasol opening, Week Strip drawing, rainbow fan opening', 'Su1800': 'mercury rising, spectrum, sparks',
    'Su1900': 'waves, Vanguard orbiting with radio rings, probe flight', 'Su2000': 'probe orbit, corona, share bar counting',
    'SuReveal': 'photon travelling, random walk drawing, 170,000 counter', 'Su2100': 'beams animating, 27 % counter, collector ring orbiting',
    'SuClose': 'sunrise wall filling', 'SuOutro': 'logo glow, Dexty.live pill, card flash',
}


def shot_at(t):
    for sid, dur, _ in B.SHOTS:
        if B.START[sid] <= t < B.START[sid] + dur:
            return sid
    return B.SHOTS[-1][0]


def main():
    words = sorted((B.VO_AT[sc] + wd['s'], wd['w']) for sc in B.VO_AT for wd in B.VO[sc]['words'])
    secs = int(B.TOTAL) + 1
    rows, flags = [], []
    for k in range(secs):
        ws = ' '.join(w for t, w in words if k <= t < k + 1)
        ev = [(t, clip, vis) for t, clip, _, vis in B.SHEET if k <= t < k + 1]
        rows.append((k, shot_at(k + 0.01), ws, ev))
    # gaps: consecutive event-free seconds while words are spoken
    ev_times = sorted(t for t, *_ in B.SHEET)
    narr = [(B.VO_AT[sc] + B.VO[sc]['words'][0]['s'], B.VO_AT[sc] + B.VO[sc]['words'][-1]['e']) for sc in B.VO_AT]
    for a, b in zip(ev_times, ev_times[1:]):
        if b - a >= GAP_S and any(n0 < b and n1 > a for n0, n1 in narr):
            flags.append((a, b))
    with open(os.path.join(WORK, 'BEATMAP.md'), 'w') as f:
        f.write('# DYK No. 02 — The Sun · BEATMAP (generated by make_beatmap.py — do not hand-edit)\n\n')
        f.write('One row per second of the master: words → visual event → SFX. Source of truth: `cues.py` '
                '(the same table `build_final.py` mixes), `timeline.json`, `remotion/src/shots/dyk-02/vo.json`.\n\n')
        f.write(f'Total {B.TOTAL:.1f} s · {len(B.SHEET)} cues · gaps ≥ {GAP_S:.1f} s between visual events while narrating: {len(flags)}\n\n')
        if flags:
            f.write('## Gaps to check (continuous motion must cover them)\n')
            for a, b in flags:
                f.write(f'- {int(a // 60)}:{a % 60:04.1f} → {int(b // 60)}:{b % 60:04.1f} ({b - a:.1f} s) in {shot_at(a)} — motion: {MOTION.get(shot_at(a), "(check)")}\n')
            f.write('\n')
        f.write('| t | shot | words | visual event (SFX) |\n|---|---|---|---|\n')
        for k, sid, ws, ev in rows:
            evs = '; '.join(f'{vis} ({clip})' for _, clip, vis in ev)
            f.write(f'| {k // 60}:{k % 60:02d} | {sid} | {ws} | {evs} |\n')
    os.makedirs(os.path.join(WORK, 'audit'), exist_ok=True)
    with open(os.path.join(WORK, 'audit', 'timeline-by-second.txt'), 'w') as f:
        f.write('sec | shot | narration in this second | SFX starting in this second\n')
        for k, sid, ws, ev in rows:
            f.write(f"{k // 60}:{k % 60:02d} | {sid} | {ws} | {', '.join(f'{clip}' for _, clip, _ in ev)}\n")
    print(f'{secs} rows, {len(flags)} gaps')
    for a, b in flags:
        print(f'  gap {a:.1f}-{b:.1f} ({b - a:.1f}s) {shot_at(a)}')


if __name__ == '__main__':
    main()

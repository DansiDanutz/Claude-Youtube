#!/usr/bin/env python3
"""GENERATE the Romanian shot copies: remotion/src/shots/dyk-05-ro/FdRo<X>.tsx from remotion/src/shots/dyk-05/Fd<X>.tsx.
Each copy is the English shot byte-for-byte except: compositionConfig.id 'Fd<X>' -> 'FdRo<X>', durationInSeconds,
`const DUR`, and every makeCue(vo, '<scene>', <offset>) offset come from ro/timeline.ro.json (the same three rewrites
work/sync_shots.py applies to the English shots from work/timeline.json), and `./vo.json` next to the copies is
ro/vo.ro.json (English words warped onto the Romanian takes), so every word-synced visual lands on the Romanian take.
The English shots are never written. The copies are never hand-edited: re-run after any change to the English shots
or to timeline.ro.json / vo.ro.json.  `--check` only reports drift (exit 1).
`--ref <git ref>` reads the English shots from that commit (git show) instead of the working tree — use the PR's base
branch so the copies never depend on uncommitted English edits in the main checkout (CI type-checks against the commit).
Run: python3 videos/dyk-05-food/ro/make_shots_ro.py [--check] [--ref video/dyk-05-food]"""
import json, os, re, shutil, subprocess, sys

RO = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(RO, '..', '..', '..'))
SRC = os.path.join(ROOT, 'remotion', 'src', 'shots', 'dyk-05')
DST = os.path.join(ROOT, 'remotion', 'src', 'shots', 'dyk-05-ro')
TL = json.load(open(os.path.join(RO, 'timeline.ro.json')))
FPS = 30
BANNER = ('// GENERATED by videos/dyk-05-food/ro/make_shots_ro.py from ../dyk-05/{sid}.tsx — DO NOT EDIT.\n'
          '// Romanian pilot of DYK No. 05: same picture, lengths and VO offsets from ro/timeline.ro.json, words from ro/vo.ro.json.\n')


def convert(sid, src):
    dur, offs = TL[sid]
    new, n_id = re.subn(r"(compositionConfig = \{ id: ')%s(', durationInSeconds: )[\d.]+" % sid,
                        lambda m: m.group(1) + ro_id(sid) + m.group(2) + f'{round(dur, 4):g}', src)
    new, n_dur = re.subn(r'const DUR = \d+;', f'const DUR = {round(dur * FPS)};', new)
    n_off = 0
    for scene, off in offs.items():
        if sid == 'FdOutro' and scene == 'fd14-endscreen':
            continue   # derived in the TSX from the outro end (same rule as make_timeline_ro.py)
        new, k = re.subn(r"(makeCue\(vo, '%s', )[\d.]+(\))" % re.escape(scene), lambda m: m.group(1) + f'{off:g}' + m.group(2), new)
        n_off += k
    expected = len(offs) - (1 if sid == 'FdOutro' else 0)
    if n_id != 1 or n_dur != 1 or n_off != expected:
        sys.exit(f'{sid}: rewrote id x{n_id}, DUR x{n_dur}, offsets {n_off}/{expected} — the English shot changed shape, update this generator')
    return BANNER.format(sid=sid) + new


def english_source(sid, ref):
    rel = f'remotion/src/shots/dyk-05/{sid}.tsx'
    if ref is None:
        return open(os.path.join(ROOT, rel), encoding='utf-8').read()
    return subprocess.run(['git', '-C', ROOT, 'show', f'{ref}:{rel}'], capture_output=True, text=True, check=True).stdout


def ro_id(sid):
    return 'FdRo' + sid[2:]


def main():
    check = '--check' in sys.argv
    ref = sys.argv[sys.argv.index('--ref') + 1] if '--ref' in sys.argv else None
    os.makedirs(DST, exist_ok=True)
    drift = []
    want = {ro_id(sid) + '.tsx' for sid in TL} | {'vo.json'}
    for sid in TL:
        out = convert(sid, english_source(sid, ref))
        path = os.path.join(DST, ro_id(sid) + '.tsx')
        if not os.path.exists(path) or open(path, encoding='utf-8').read() != out:
            drift.append(ro_id(sid))
            if not check:
                open(path, 'w', encoding='utf-8').write(out)
    vo_src, vo_dst = os.path.join(RO, 'vo.ro.json'), os.path.join(DST, 'vo.json')
    if not os.path.exists(vo_dst) or open(vo_dst, 'rb').read() != open(vo_src, 'rb').read():
        drift.append('vo.json')
        if not check:
            shutil.copyfile(vo_src, vo_dst)
    stray = sorted(set(os.listdir(DST)) - want - {'README.md'})
    if stray:
        print('stray files in dyk-05-ro (not generated, not removed):', ', '.join(stray))
    print(('drift in: ' if check else 'generated: ') + (', '.join(drift) or 'none') + f' ({len(TL)} shots, English from {ref or "working tree"})')
    sys.exit(1 if check and drift else 0)


if __name__ == '__main__':
    main()

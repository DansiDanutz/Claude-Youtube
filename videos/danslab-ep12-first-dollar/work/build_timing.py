#!/usr/bin/env python3
"""Single source of EP12 timing. Reads the REAL dol wav durations (ffprobe) + whisper word timestamps
(verify/words/*.json) and writes remotion/src/lib/ep12timing.gen.ts, which every W* shot imports:
  SHOT_SEC[id]  — shot length (s) = last VO end + TAIL
  at(vo, word, nth) — frame (in the shot) where that word starts, so reveals land ON the narrator's word
  voAt(vo) / voEnd(vo) — frames where a line starts / ends inside its shot
Also prints the ORDER offsets for assemble.py (VO offsets inside each shot). Re-run after any re-voice."""
import json, os, re, subprocess, sys
WORK = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(WORK)))
FPS, FIRST, GAP, TAIL = 30, 0.7, 0.5, 1.3
PLAN = [  # (shot, [vo ids]) — keep in step with assemble.ORDER and SCRIPT.md
 ("WDollar",["dol01","dol02","dol03"]),("WIntro",[]),("WStakes",["dol04"]),
 ("WNewCrew",["dol05"]),("WRebuilt",["dol06"]),("WWhy",["dol07"]),("WTurn",["dol08"]),("WLandlord",["dol09"]),
 ("WOwnRail",["dol10"]),("WInstant",["dol11"]),("WForYou",["dol12"]),("WStable",["dol13"]),("WNoBank",["dol14"]),
 ("WAgentMoney",["dol15"]),("WHonestDeps",["dol16"]),("WSetup",["dol17"]),("WScan",["dol18"]),("WReceipts",["dol19"]),
 ("WAudit",["dol20"]),("WMoment",["dol21"]),("WOffer",["dol22"]),("WLands",["dol23a"]),("WFails",["dol23b"]),
 ("WHuman",["dol24"]),("WNext",["dol25"]),("WOutro",["dol26"]),
]
FIXED = {"WIntro": 13.0}
BRANCH = "WFails" if "--fails" in sys.argv else "WLands"
EST = {"dol23a": 15.0, "dol23b": 12.0}   # not voiced yet (real attempt first) — placeholder lengths, flagged below

def dur(p):
    return float(subprocess.run(["ffprobe","-v","error","-show_entries","format=duration","-of","csv=p=0",p],
                                capture_output=True,text=True).stdout.strip())

def clean(w):
    return re.sub(r"[^a-z0-9$%']", "", w.lower())

shots, vos, order, flags = {}, {}, [], []
for shot, ids in PLAN:
    t, offs = (0.6 if shot == "WOutro" else FIRST), []
    for v in ids:
        wav = os.path.join(WORK, "mix", f"{v}.wav")
        if os.path.exists(wav):
            d = dur(wav)
            j = json.load(open(os.path.join(WORK, "verify", "words", f"{v}.json")))
            words = [(clean(w["word"]), round(w["start"], 3)) for s in j["segments"] for w in s.get("words", [])]
        else:
            d, words = EST[v], []
            flags.append(f"{v}: not voiced — {shot} uses an estimated {d}s; rebuild after voicing")
        vos[v] = {"shot": shot, "off": round(t, 3), "dur": round(d, 3), "words": words}
        offs.append((v, round(t, 2)))
        t += d + GAP
    end = (t - GAP) if ids else 0
    shots[shot] = FIXED.get(shot, round(-(-(end + TAIL) * 10 // 1) / 10, 1))
    order.append((shot, offs))

ts = ["// GENERATED by videos/danslab-ep12-first-dollar/work/build_timing.py — do not edit by hand.",
      "// Source: real dol*.wav durations + whisper word timestamps. Re-run the script after any re-voice.",
      f"export const FPS = {FPS};",
      "export const SHOT_SEC: Record<string, number> = " + json.dumps(shots) + ";",
      "type Vo = { shot: string; off: number; dur: number; words: [string, number][] };",
      "export const VO: Record<string, Vo> = " + json.dumps(vos, separators=(",", ":")) + ";",
      "const f = (s: number) => Math.round(s * FPS);",
      "/** frame (inside the line's shot) where the line starts */",
      "export const voAt = (vo: string) => f(VO[vo].off);",
      "/** frame (inside the line's shot) where the line ends */",
      "export const voEnd = (vo: string) => f(VO[vo].off + VO[vo].dur);",
      "/** frame (inside the shot) where the nth occurrence of `word` starts in line `vo`.",
      " *  Throws if the word isn't heard — a wrong cue must fail the render, not drift silently.",
      " *  Unvoiced lines (no words yet) fall back to `fallbackSec` into the line. */",
      "export const at = (vo: string, word: string, nth = 1, fallbackSec?: number): number => {",
      "  const v = VO[vo];",
      "  if (!v.words.length && fallbackSec !== undefined) return f(v.off + fallbackSec);",
      "  const hits = v.words.filter(([w]) => w === word.toLowerCase());",
      "  if (hits.length < nth) throw new Error(`ep12timing: '${word}' #${nth} not heard in ${vo}`);",
      "  return f(v.off + hits[nth - 1][1]);",
      "};",
      "export const secs = (id: string) => SHOT_SEC[id];",
      "/** shot order of the cut (the WLands branch by default — set BRANCH to 'WFails' if the money didn't land) */",
      "export const BRANCH: 'WLands' | 'WFails' = " + json.dumps(BRANCH) + ";",
      "export const CUT: string[] = " + json.dumps([s for s, _ in order if s != ("WFails" if BRANCH == "WLands" else "WLands")]) + ";",
      "/** absolute second (final timeline) where a shot starts */",
      "export const shotStart = (id: string) => { let t = 0; for (const s of CUT) { if (s === id) return t; t += SHOT_SEC[s]; } throw new Error(`ep12timing: ${id} not in cut`); };",
      "/** absolute frame (final timeline) of an in-shot frame */",
      "export const abs = (shot: string, frameInShot: number) => Math.round(shotStart(shot) * FPS) + frameInShot;",
      "export const TOTAL_SEC = CUT.reduce((a, s) => a + SHOT_SEC[s], 0);", ""]
out = os.path.join(REPO, "remotion", "src", "lib", "ep12timing.gen.ts")
open(out, "w").write("\n".join(ts))
json.dump({"branch": BRANCH, "shots": shots, "vo": {v: {"shot": d["shot"], "off": d["off"], "dur": d["dur"]} for v, d in vos.items()}},
          open(os.path.join(WORK, "timing.json"), "w"), indent=1)
# compositionConfig durations must be LITERALS (gen-registry parses them by regex) — patch them from the real audio
SHOTDIR = os.path.join(REPO, "remotion", "src", "shots", "danslab-ep12")
total = sum(shots[s] for s, _ in order if s != ("WFails" if BRANCH == "WLands" else "WLands"))
want = dict(shots, WHud=round(total + 1, 1), WHudTop=round(total + 1, 1))
for sid, sec in want.items():
    f = os.path.join(SHOTDIR, f"{sid}.tsx")
    if not os.path.exists(f):
        continue
    src = open(f).read()
    new = re.sub(r"(id: '" + sid + r"',\s*durationInSeconds:\s*)[0-9.]+", lambda m: m.group(1) + f"{sec:g}", src, count=1)
    if new != src:
        open(f, "w").write(new); print(f"  patched {sid}.tsx durationInSeconds={sec:g}")
print(f"wrote {out}")
for s, o in order:
    print(f"  {s:12} {shots[s]:5.1f}s  " + ", ".join(f"{v}@{t}" for v, t in o))
print(f"total {sum(shots[s] for s, _ in order if s != 'WFails'):.1f}s (WLands branch)")
for x in flags: print("FLAG", x)
if "--words" in sys.argv:
    for v, d in vos.items():
        print(v, " ".join(f"{w}@{s:.1f}" for w, s in d["words"]))

#!/usr/bin/env python3
"""BEATMAP skeleton for DYK No. 07: one row per second of the master, with the shot and the words Brian speaks in that
second, from the same data the mix uses (timeline.json + remotion/src/shots/dyk-07/vo.json). The VISUAL and SFX columns
are left empty for the shot design (skill: design every second before rendering). Once cue_parts/ exist, Ep 05's
make_beatmap.py (via build_final) replaces this file with the full map and its empty-stretch flags."""
import json, math, os

WORK = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(WORK, "..", "..", ".."))
TL = json.load(open(os.path.join(WORK, "timeline.json")))
VO = json.load(open(os.path.join(ROOT, "remotion", "src", "shots", "dyk-07", "vo.json")))


def rows():
    """One row per second. Words are gathered across all shots first, so a second shared by two shots keeps both
    shots' words and names both shots."""
    t0, spans, words = 0.0, [], []
    for shot, (dur, offs) in TL.items():
        spans.append((t0, t0 + dur, shot))
        for sid, off in offs.items():
            words += [(t0 + off + w["s"], w["w"]) for w in VO[sid]["words"]]
        t0 += dur
    words.sort()
    out = []
    for sec in range(math.ceil(t0 - 1e-6)):
        shots = " / ".join(shot for a, b, shot in spans if a < sec + 1 - 1e-6 and b > sec + 1e-6)
        said = " ".join(w for s, w in words if sec <= s < sec + 1)
        out.append((sec, shots, said))
    return out, t0


def main():
    table, total = rows()
    lines = ["# No. 07 Medicine · BEATMAP (skeleton)", "",
             f"Generated by `make_beat_skeleton.py` from timeline.json and vo.json. Master {total:.1f} s "
             f"({int(total // 60)}:{total % 60:04.1f}). Fill VISUAL (enter on the word, hold >= 1.5 s, nothing spoils its word) "
             "and SFX (marks the visual, never on a word onset) for every narrated second before writing a shot.", "",
             "| s | m:ss | shot | words | visual | sfx |", "|---|---|---|---|---|---|"]
    for sec, shot, said in table:
        lines.append(f"| {sec} | {sec // 60}:{sec % 60:02d} | {shot} | {said} |  |  |")
    open(os.path.join(WORK, "BEATMAP.md"), "w").write("\n".join(lines) + "\n")
    narrated = sum(1 for _, _, s in table if s)
    print(f"BEATMAP.md: {len(table)} rows, {narrated} with speech, master {total:.1f} s")


if __name__ == "__main__":
    main()
